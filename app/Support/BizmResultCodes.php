    public static function describe(?string $raw): ?string
    {
        if ($raw === null || ! preg_match('/\b([KMER]\d{3})\b/', $raw, $m) || ! isset(self::CODES[$m[1]])) {
            return null;
        }

        return $m[1].' — '.self::CODES[$m[1]];
    }
