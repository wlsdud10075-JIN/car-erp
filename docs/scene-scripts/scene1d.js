  await p.goto('http://localhost:8001/erp/vehicles?search=' + encodeURIComponent(PLATE), { waitUntil: 'networkidle' });
  await open();
  const d = p.locator('input[wire\\:model="purchase_date"], input[wire\\:model\\.blur="purchase_date"], input[wire\\:model\\.live="purchase_date"]').first();
