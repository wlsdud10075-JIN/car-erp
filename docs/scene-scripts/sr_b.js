const { chromium } = require('playwright-core');
const raw = __dirname + '/sr/';
const PLATE = '00가1113';
const panel = { x: 460, y: 0, width: 820 };
(async () => {
  const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
  const ctx = await b.newContext({ viewport: { width: 1280, height: 1000 }, locale: 'ko-KR', deviceScaleFactor: 1.5, acceptDownloads: true });
  const p = await ctx.newPage();
  await p.goto('http://localhost:8001/login');
  await p.fill('input[type=email]', 'manage@car-erp.test');
  await p.fill('input[type=password]', 'password');
  await Promise.all([p.waitForLoadState('networkidle'), p.keyboard.press('Enter')]);
  await p.goto('http://localhost:8001/erp/vehicles?search=' + encodeURIComponent(PLATE), { waitUntil: 'networkidle' });
  await p.locator('tr', { hasText: PLATE }).first().locator('td').nth(1).click();
  await p.waitForTimeout(2500);
  await p.click(`button[\\@click="tab = 'sale'"]`);
  await p.waitForTimeout(600);
  const sm = p.getByText('판매 미입금 요약').first();
  await sm.evaluate(e => e.scrollIntoView({ block: 'center' }));
  await p.waitForTimeout(500);
  const sb = await sm.boundingBox();
  await p.screenshot({ path: raw + 't1-summary.png', clip: { ...panel, y: sb.y - 20, height: 200 } });
  await p.click(`button[\\@click="tab = 'docs'"]`);
  await p.waitForTimeout(800);
  const inv = p.locator('a[href*="/documents/invoice"]').first();
  console.log('invoice tag', await inv.evaluate(e => e.tagName + ' ' + (e.getAttribute('href') || e.getAttribute('wire:click') || '')));
  const [dl] = await Promise.all([p.waitForEvent('download', { timeout: 30000 }), inv.click()]);
  const path = raw + 'invoice.xlsx';
  await dl.saveAs(path);
  console.log('download', dl.suggestedFilename());
  await b.close();
})().catch(e => { console.error(e); process.exit(1); });
