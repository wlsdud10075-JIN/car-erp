const { chromium } = require('playwright-core');
const raw = __dirname + '/rv/';
require('fs').mkdirSync(raw, { recursive: true });
(async () => {
  const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
  const p = await (await b.newContext({ viewport: { width: 1280, height: 1000 }, locale: 'ko-KR', deviceScaleFactor: 1.5 })).newPage();
  p.setDefaultTimeout(60000);
  await p.goto('http://localhost:8001/login');
  await p.fill('input[type=email]', 'finance@car-erp.test');
  await p.fill('input[type=password]', 'password');
  await Promise.all([p.waitForLoadState('networkidle'), p.keyboard.press('Enter')]);
  await p.goto('http://localhost:8001/erp/receivables', { waitUntil: 'networkidle', timeout: 120000 });
  await p.screenshot({ path: raw + 'e0-top.png', fullPage: false });
  console.log('inputs:', JSON.stringify(await p.$$eval('input:visible,select:visible', e => e.map(x => [x.tagName, x.getAttribute('wire:model') || x.getAttribute('wire:model.live') || x.getAttribute('x-model'), x.placeholder || '']).slice(0, 20))));
  const s = p.locator('input[wire\\:model="search"], input[wire\\:model\\.live="search"]').first();
  await s.fill('00가1131');
  await p.getByRole('button', { name: '조회', exact: true }).click().catch(() => console.log('no 조회'));
  await p.waitForTimeout(2000);
  await p.screenshot({ path: raw + 'e1-list.png', fullPage: true });
  const row = p.locator('tr', { hasText: '00가1131' }).first();
  console.log('row:', (await row.innerText()).replace(/\s+/g, ' '));
  await row.locator('td').nth(1).click();
  await p.waitForTimeout(2500);
  await p.screenshot({ path: raw + 'e2-panel.png', fullPage: false });
  const t = await p.locator('body').innerText();
  const i = t.indexOf('00가1131', t.indexOf('00가1131') + 10);
  console.log('--- panel ---\n' + t.slice(Math.max(0, i - 200), i + 3000));
  console.log('panel inputs:', JSON.stringify(await p.$$eval('[wire\\:model^="h"], [wire\\:model\\.live^="h"]', e => e.map(x => [x.tagName, x.getAttribute('wire:model') || x.getAttribute('wire:model.live'), x.type]))));
  console.log('buttons:', JSON.stringify(await p.$$eval('button:visible', e => e.map(x => [x.innerText.trim().replace(/\s+/g, ' ').slice(0, 30), x.getAttribute('wire:click')]).filter(x => x[1]).slice(0, 40))));
  await b.close();
})().catch(e => { console.error(e.message.slice(0, 400)); process.exit(1); });
