const { chromium } = require('playwright-core');
const raw = __dirname + '/inv/';
const PLATE = '00가1161';
(async () => {
  const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
  const p = await (await b.newContext({ viewport: { width: 1600, height: 1000 }, locale: 'ko-KR', deviceScaleFactor: 1.5 })).newPage();
  p.setDefaultTimeout(90000);
  const body = async (re) => { const t = await p.locator('body').innerText(); const m = t.match(re); return m ? m[0] : '(없음)'; };
  await p.goto('http://localhost:8001/login');
  await p.fill('input[type=email]', 'clear@car-erp.test');
  await p.fill('input[type=password]', 'password');
  await Promise.all([p.waitForLoadState('networkidle'), p.keyboard.press('Enter')]);
  const hideAlarm = async () => { await p.evaluate(() => { for (const el of document.querySelectorAll('*')) { if (el.children.length === 0 && /통관서류 알람/.test(el.textContent || '')) { let a = el; while (a && getComputedStyle(a).position !== 'fixed') a = a.parentElement; if (a) a.style.display = 'none'; } } }); };
  const go = async (cat) => {
    await p.goto('http://localhost:8001/erp/inventory' + (cat ? '?category=' + cat : ''), { waitUntil: 'networkidle', timeout: 120000 });
    await p.locator('input[wire\\:model="search"]').first().fill(PLATE);
    await p.getByRole('button', { name: '조회', exact: true }).click();
    await p.waitForTimeout(1800);
    await hideAlarm();
  };
  await go('');
  await p.screenshot({ path: raw + 'n1-list.png', fullPage: true });
  const row = () => p.locator('tr', { hasText: PLATE }).first();
  console.log('row:', (await row().innerText()).replace(/\s+/g, ' '));
  await row().locator('button', { hasText: '야드' }).first().evaluate(e => e.click());
  await p.waitForTimeout(600);
  await row().locator('input[wire\\:model^="stockLocationNote"]').fill('A-3 구역');
  await p.waitForTimeout(400);
  await p.screenshot({ path: raw + 'n2-picked.png', fullPage: true });
  await p.locator('button[wire\\:click="applyWarehouseOut"]').first().evaluate(e => e.click());
  await p.waitForTimeout(2500);
  console.log('apply1:', await body(/[^\n]*(적용|저장|바꿨|했습니다)[^\n]*/));
  await go('');
  await p.screenshot({ path: raw + 'n3-saved.png', fullPage: true });
  console.log('row2:', (await row().innerText()).replace(/\s+/g, ' '));
  // 출고일
  const out = row().locator('input[wire\\:model^="warehouseOut"]').first();
  await out.fill('2026-11-14');
  await p.keyboard.press('Tab');
  await p.waitForTimeout(400);
  await p.screenshot({ path: raw + 'n4-out.png', fullPage: true });
  await p.locator('button[wire\\:click="applyWarehouseOut"]').first().evaluate(e => e.click());
  await p.waitForTimeout(2500);
  console.log('apply2:', await body(/[^\n]*(적용|저장|바꿨|했습니다)[^\n]*/));
  await go('shipped_out');
  await p.screenshot({ path: raw + 'n5-shipped.png', fullPage: true });
  console.log('shipped row:', (await row().innerText().catch(() => '(없음)')).replace(/\s+/g, ' '));
  await b.close();
})().catch(e => { console.error(e.message.slice(0, 400)); process.exit(1); });
