const { chromium } = require('playwright-core');
const raw = __dirname + '/bk/';
(async () => {
  const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
  const p = await (await b.newContext({ viewport: { width: 1600, height: 1000 }, locale: 'ko-KR', deviceScaleFactor: 1.5 })).newPage();
  p.setDefaultTimeout(90000);
  p.on('dialog', d => { console.log('dialog:', d.message().slice(0, 200)); d.accept(); });
  await p.goto('http://localhost:8001/login');
  await p.fill('input[type=email]', 'finance@car-erp.test');
  await p.fill('input[type=password]', 'password');
  await Promise.all([p.waitForLoadState('networkidle'), p.keyboard.press('Enter')]);
  await p.goto('http://localhost:8001/erp/dashboard', { waitUntil: 'networkidle', timeout: 120000 });
  await p.waitForTimeout(3000);
  const card = () => p.locator('[data-cash-card]').first();
  const addAcc = async (bank, no, label, foreign) => {
    await card().locator('button', { hasText: '+ 계좌 추가' }).first().evaluate(e => e.click());
    await p.waitForTimeout(1200);
    await card().locator('input[wire\\:model="newBank"]').first().fill(bank);
    await card().locator('input[wire\\:model="newAccountNo"]').first().fill(no);
    await card().locator('input[wire\\:model="newLabel"]').first().fill(label);
    if (foreign) await card().locator('input[wire\\:model="newForeign"]').first().check();
    await p.waitForTimeout(400);
    await card().screenshot({ path: raw + 'k1-add-' + label + '.png' });
    await card().locator('button[wire\\:click="addCashAccount"]').first().evaluate(e => e.click());
    await p.waitForTimeout(2500);
  };
  await addAcc('예시', '000-000-000001', '업무', false);
  await addAcc('예시', '000-000-000002', '외화', true);
  await card().scrollIntoViewIfNeeded();
  await card().screenshot({ path: raw + 'k2-two.png' });
  const pick = async (no) => {
    const sel = card().locator('select[wire\\:model\\.live="cashAccountId"]').first();
    const val = await sel.locator('option', { hasText: no }).first().getAttribute('value');
    await sel.selectOption(val);
    await p.waitForTimeout(2000);
  };
  await pick('000001');
  await card().locator('input[wire\\:model="cashAmounts.KRW"]').first().fill('52,340,000');
  await p.waitForTimeout(400);
  await card().screenshot({ path: raw + 'k3-krw.png' });
  await card().locator('button[wire\\:click="saveAccountBalance"]').first().evaluate(e => e.click());
  await p.waitForTimeout(2500);
  await pick('000002');
  await card().locator('input[wire\\:model="cashAmounts.USD"]').first().fill('12500');
  await card().locator('input[wire\\:model="cashAmounts.EUR"]').first().fill('3000');
  await p.waitForTimeout(400);
  await card().screenshot({ path: raw + 'k4-fx.png' });
  await card().locator('button[wire\\:click="saveAccountBalance"]').first().evaluate(e => e.click());
  await p.waitForTimeout(3000);
  await card().screenshot({ path: raw + 'k5-saved.png' });
  console.log((await card().innerText()).slice(0, 1800));
  await b.close();
})().catch(e => { console.error(e.message.slice(0, 400)); process.exit(1); });
