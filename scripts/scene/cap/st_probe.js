const { chromium } = require('playwright-core');
const PLATE = '70가7001';
(async () => {
  const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
  const p = await (await b.newContext({ viewport: { width: 1280, height: 1000 }, locale: 'ko-KR', deviceScaleFactor: 1.5 })).newPage();
  p.setDefaultTimeout(90000);
  await p.goto('http://localhost:8001/login');
  await p.fill('input[type=email]', 'finance@car-erp.test');
  await p.fill('input[type=password]', 'password');
  await Promise.all([p.waitForLoadState('networkidle'), p.keyboard.press('Enter')]);
  await p.goto('http://localhost:8001/erp/settlements?monthFilter=2026-07', { waitUntil: 'networkidle', timeout: 120000 });
  await p.locator('input[wire\\:model="search"], input[wire\\:model\\.live="search"]').first().fill(PLATE);
  await p.getByRole('button', { name: '조회', exact: true }).click();
  await p.waitForTimeout(2000);
  const row = p.locator('tr', { hasText: PLATE }).first();
  console.log('row:', (await row.innerText()).replace(/\s+/g, ' '));
  await p.screenshot({ path: __dirname + '/st-list.png', fullPage: true });
  await row.locator('td').nth(1).click();
  await p.waitForTimeout(2500);
  const t = await p.locator('body').innerText();
  const i = t.indexOf('정산 수정');
  console.log(t.slice(i, i + 2500));
  await p.screenshot({ path: __dirname + '/st-drawer.png' });
  await b.close();
})().catch(e => { console.error(e.message.slice(0, 300)); process.exit(1); });
