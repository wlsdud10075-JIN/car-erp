const { chromium } = require('playwright-core');
const raw = __dirname + '/ba/';
const BUYER = 'GUIDE SAMPLE TRADING';
(async () => {
  const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
  const p = await (await b.newContext({ viewport: { width: 1280, height: 1000 }, locale: 'ko-KR', deviceScaleFactor: 1.5 })).newPage();
  p.setDefaultTimeout(90000);
  await p.goto('http://localhost:8001/login');
  await p.fill('input[type=email]', 'finance@car-erp.test');
  await p.fill('input[type=password]', 'password');
  await Promise.all([p.waitForLoadState('networkidle'), p.keyboard.press('Enter')]);
  await p.goto('http://localhost:8001/erp/buyers?search=' + encodeURIComponent(BUYER), { waitUntil: 'networkidle', timeout: 120000 });
  await p.waitForTimeout(1500);
  await p.locator('tr', { hasText: BUYER }).first().click();
  await p.waitForTimeout(2500);
  await p.locator('button', { hasText: /^현금$/ }).first().click();
  await p.waitForTimeout(1000);
  await p.getByRole('button', { name: /수수료$/ }).first().click();
  await p.waitForTimeout(1200);
  await p.screenshot({ path: raw + 'f1-fee-open.png' });
  await p.locator('input[wire\\:model="fee_amount"]').fill('25');
  await p.locator('input[wire\\:model="fee_note"]').fill('중계은행 수수료');
  const btn = p.locator('button[wire\\:click="addCashFee"]');
  await btn.scrollIntoViewIfNeeded();
  await p.waitForTimeout(400);
  await p.screenshot({ path: raw + 'f2-fee-filled.png' });
  await btn.click();
  await p.waitForTimeout(2500);
  const t = await p.locator('body').innerText();
  console.log((t.match(/[^\n]*수수료[^\n]*(했|됐)[^\n]*/) || ['(없음)'])[0]);
  await p.locator('text=통화별 현금').first().scrollIntoViewIfNeeded();
  await p.screenshot({ path: raw + 'f3-fee-saved.png' });
  await p.mouse.wheel(0, 700);
  await p.waitForTimeout(600);
  await p.screenshot({ path: raw + 'f4-fee-list.png' });
  await b.close();
})().catch(e => { console.error(e.message.slice(0, 300)); process.exit(1); });
